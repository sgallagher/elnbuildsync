parse_commandline()
{
	_positionals_count=0
	local _key
	while test $# -gt 0
	do
		_key="$1"
		if test "$_key" = '--'
		then
			shift
			test $# -gt 0 || break
			_positionals+=("$@")
			_positionals_count=$((_positionals_count + $#))
			shift $(($# - 1))
			_last_positional="$1"
			break
		fi
		case "$_key" in
			--log-level)
				test $# -lt 2 && die "Missing value for the optional argument '$_key'." 1
				_arg_log_level="$2"
				shift
				;;
			--log-level=*)
				_arg_log_level="${_key##--log-level=}"
				;;
			--db-pw-file)
				test $# -lt 2 && die "Missing value for the optional argument '$_key'." 1
				_arg_db_pw_file="$2"
				shift
				;;
			--db-pw-file=*)
				_arg_db_pw_file="${_key##--db-pw-file=}"
				;;
			--smtp-pw-file)
				test $# -lt 2 && die "Missing value for the optional argument '$_key'." 1
				_arg_smtp_pw_file="$2"
				shift
				;;
			--smtp-pw-file=*)
				_arg_smtp_pw_file="${_key##--smtp-pw-file=}"
				;;
			--openid-client-secret-file)
				test $# -lt 2 && die "Missing value for the optional argument '$_key'." 1
				_arg_openid_client_secret_file="$2"
				shift
				;;
			--openid-client-secret-file=*)
				_arg_openid_client_secret_file="${_key##--openid-client-secret-file=}"
				;;
			--openid-ca-file)
				test $# -lt 2 && die "Missing value for the optional argument '$_key'." 1
				_arg_openid_ca_file="$2"
				shift
				;;
			--openid-ca-file=*)
				_arg_openid_ca_file="${_key##--openid-ca-file=}"
				;;
			--lull-time)
				test $# -lt 2 && die "Missing value for the optional argument '$_key'." 1
				_arg_lull_time="$2"
				shift
				;;
			--lull-time=*)
				_arg_lull_time="${_key##--lull-time=}"
				;;
			--static-config-file)
				test $# -lt 2 && die "Missing value for the optional argument '$_key'." 1
