			--static-config-file=*)
				_arg_static_config_file="${_key##--static-config-file=}"
				;;
			--dynamic-config-file)
				test $# -lt 2 && die "Missing value for the optional argument '$_key'." 1
				_arg_dynamic_config_file="$2"
				shift
				;;
			--dynamic-config-file=*)
				_arg_dynamic_config_file="${_key##--dynamic-config-file=}"
				;;
			--environment)
				test $# -lt 2 && die "Missing value for the optional argument '$_key'." 1
				_arg_environment="$2"
				shift
				;;
			--environment=*)
				_arg_environment="${_key##--environment=}"
				;;
			--krb5-keytab-file)
				test $# -lt 2 && die "Missing value for the optional argument '$_key'." 1
				_arg_krb5_keytab_file="$2"
				shift
				;;
			--krb5-keytab-file=*)
				_arg_krb5_keytab_file="${_key##--krb5-keytab-file=}"
				;;
			--krb5-keytab-principal)
				test $# -lt 2 && die "Missing value for the optional argument '$_key'." 1
				_arg_krb5_keytab_principal="$2"
				shift
				;;
			--krb5-keytab-principal=*)
				_arg_krb5_keytab_principal="${_key##--krb5-keytab-principal=}"
				;;
			--no-persistent-db|--persistent-db)
				_arg_persistent_db="on"
				test "${1:0:5}" = "--no-" && _arg_persistent_db="off"
